// ############################################################################
// Hundreds of thousands of rows, generated by the suite itself.
//
// Everything else in this directory reads a handful of rows, which all arrive
// in ONE Arrow record batch. That is a single trip through BE's materialize
// loop, so it says nothing about the loop -- about a column buffer reused
// across batches, an offset accumulated per batch instead of per row, or a
// stream ended one batch early. Those defects are invisible below a few
// thousand rows and silent above them: the query returns, with fewer or
// repeated rows.
//
// So the assertions are all about CONSERVATION, and they are chosen so that no
// single defect satisfies all of them:
//   count(*)          catches losing rows, misses losing one and repeating one
//   count(DISTINCT)   catches repeating rows, misses losing a whole batch
//   sum / min / max   catch a batch read at the wrong offset
// Together they do not have a blind spot that a plausible batching bug fits
// through.
//
// Both sources get the same treatment, because they reach the batch loop
// differently: a Doris source over Flight SQL streams partitions of a query it
// already executed, while SQLite streams one statement's result from a local
// file. Neither driver is required -- each section is skipped on its own, with
// a log that says what stopped being tested.
// ############################################################################

suite("test_adbc_large_data", "p0,external") {
    String repoRoot = new File(context.config.suitePath).getParentFile().getParentFile()
            .getAbsolutePath()
    String thirdparty = System.getenv("DORIS_THIRDPARTY")
    if (thirdparty == null || thirdparty.isEmpty()) {
        thirdparty = "${repoRoot}/thirdparty"
    }
    String flightDriverPath = context.config.otherConfigs.get("adbcDriverPath")
    if (flightDriverPath == null || flightDriverPath.isEmpty()) {
        flightDriverPath = "${thirdparty}/installed/lib64/libadbc_driver_flightsql.so"
    }
    String sqliteDriverPath = context.config.otherConfigs.get("adbcSqliteDriverPath")
    if (sqliteDriverPath == null || sqliteDriverPath.isEmpty()) {
        sqliteDriverPath = "${thirdparty}/installed/lib64/libadbc_driver_sqlite.so"
    }

    boolean hasFlight = new File(flightDriverPath).canRead()
    boolean hasSqlite = new File(sqliteDriverPath).canRead()
    if (!hasFlight && !hasSqlite) {
        logger.info("SKIPPED test_adbc_large_data: no readable ADBC driver at ${flightDriverPath} or "
                + "${sqliteDriverPath}. Install them with 'cd thirdparty && ./build-thirdparty.sh "
                + "arrow_adbc'. MULTI-BATCH ADBC READS ARE NOT BEING TESTED.")
        return
    }

    String flightCatalog = "test_adbc_large_data_flight"
    String flightSingleRange = "test_adbc_large_data_flight_single"
    String sqliteCatalog = "test_adbc_large_data_sqlite"
    String dbName = "test_adbc_large_data_db"

    sql """DROP CATALOG IF EXISTS ${flightCatalog}"""
    sql """DROP CATALOG IF EXISTS ${flightSingleRange}"""
    sql """DROP CATALOG IF EXISTS ${sqliteCatalog}"""

    try {
        // ---- a Doris source over Arrow Flight SQL ----

        if (!hasFlight) {
            logger.info("test_adbc_large_data: SKIPPING the Flight SQL section, no driver at "
                    + "${flightDriverPath}. LARGE PARTITIONED READS ARE NOT BEING TESTED.")
        } else {
            int rows = 200000
            def frontends = sql "show frontends"
            String arrowPort = frontends[0][6]

            sql """DROP DATABASE IF EXISTS internal.${dbName} FORCE"""
            sql """CREATE DATABASE internal.${dbName}"""

            // Twelve columns rather than three: a wide row makes each record batch larger and forces more
            // of them for the same row count, and it is where a per-column buffer reused across batches
            // shows up.
            sql """
                CREATE TABLE internal.${dbName}.big (
                  `id` int NOT NULL,
                  `name` varchar(64) NULL,
                  `grp` int NULL,
                  `amount` decimalv3(18, 4) NULL,
                  `ratio` double NULL,
                  `flag` boolean NULL,
                  `big_id` bigint NULL,
                  `d` date NULL,
                  `ts` datetime(3) NULL,
                  `pad_a` varchar(128) NULL,
                  `pad_b` varchar(128) NULL,
                  `maybe_null` varchar(64) NULL
                ) DISTRIBUTED BY HASH(`id`) BUCKETS 8
                PROPERTIES ("replication_num" = "1")
            """
            // maybe_null is null on nine rows out of ten: a null bitmap that is rebuilt per batch rather
            // than per row goes wrong here and nowhere in a dense fixture.
            sql """
                INSERT INTO internal.${dbName}.big
                SELECT number,
                       concat('name-', number),
                       number % 97,
                       number / 7,
                       number / 3.0,
                       number % 2 = 0,
                       number * 1000000,
                       date_add(CAST('2000-01-01' AS date), INTERVAL (number % 9000) DAY),
                       date_add(CAST('2000-01-01 00:00:00' AS datetime(3)), INTERVAL (number % 100000) SECOND),
                       concat('pad-a-', repeat('x', 20), number),
                       concat('pad-b-', repeat('y', 20), number),
                       CASE WHEN number % 10 = 0 THEN concat('v', number) ELSE NULL END
                FROM numbers("number" = "${rows}")
            """

            sql """
                CREATE CATALOG ${flightCatalog} PROPERTIES (
                    "type" = "adbc",
                    "driver_url" = "${flightDriverPath}",
                    "uri" = "grpc://127.0.0.1:${arrowPort}",
                    "user" = "root",
                    "password" = "",
                    "partitioned_read" = "required"
                )
            """
            String table = "${flightCatalog}.${dbName}.big"

            // The conservation checks, against the source table itself. The right answer is known here, so
            // a fault shared by both read paths cannot hide inside an agreement between two ADBC reads.
            def conserved = { String columns, String where ->
                def viaAdbc = sql("SELECT ${columns} FROM ${table} ${where}")
                def viaSource = sql("SELECT ${columns} FROM internal.${dbName}.big ${where}")
                assertEquals(viaSource.toString(), viaAdbc.toString(),
                        "a ${rows}-row read disagreed with the source on [${columns} ${where}]")
                return viaAdbc
            }

            // count(*) projects no columns at all, so it also covers BE counting rows across many batches
            // without materialising any.
            assertEquals(rows as long, sql("SELECT count(*) FROM ${table}")[0][0],
                    "a ${rows}-row table did not come back with ${rows} rows")

            conserved("count(*), count(DISTINCT id), sum(id), min(id), max(id)", "")
            // The null column: count() ignores nulls, so this is what pins the null bitmap.
            conserved("count(maybe_null), count(DISTINCT maybe_null), min(maybe_null), max(maybe_null)", "")
            // Strings, where a mis-sliced offset buffer produces values that are wrong rather than missing.
            conserved("count(DISTINCT name), min(name), max(name)", "")
            conserved("count(DISTINCT pad_a), min(pad_b), max(pad_b)", "")
            // Every remaining type family across every batch.
            conserved("sum(amount), min(amount), max(amount)", "")
            conserved("min(ratio), max(ratio)", "")
            // sum() over DOUBLE is the one comparison in this suite that cannot be exact, and the
            // reason is the very thing the suite exercises: the ADBC read is split into partitions
            // whose partial sums are added in a different order than the source's scan produces, and
            // floating-point addition is not associative. The two totals differ in the last bits
            // (~1e-15 relative) for that reason alone -- comparing them as strings reports a
            // rounding artefact as a data fault. The tolerance below is thousands of times that
            // difference and still far below what one lost or repeated row moves the total by, so
            // this remains a conservation check.
            double adbcRatioSum = sql("SELECT sum(ratio) FROM ${table}")[0][0] as double
            double sourceRatioSum = sql("SELECT sum(ratio) FROM internal.${dbName}.big")[0][0] as double
            assertTrue(Math.abs(adbcRatioSum - sourceRatioSum) <= Math.abs(sourceRatioSum) * 1e-11,
                    "a ${rows}-row read disagreed with the source on sum(ratio) by more than "
                            + "floating-point summation order can explain: ADBC ${adbcRatioSum} "
                            + "vs source ${sourceRatioSum}")
            conserved("count(DISTINCT flag), sum(CASE WHEN flag THEN 1 ELSE 0 END)", "")
            conserved("sum(big_id), min(big_id), max(big_id)", "")
            conserved("min(d), max(d), count(DISTINCT d)", "")
            // ts is cast back to the source's type first: a Doris source stamps the session zone onto
            // every DATETIMEV2 it writes to Arrow, so the column arrives as TIMESTAMPTZ and prints an
            // offset the native read does not. The cast is a no-op on the source side, leaving the
            // instants -- and the DISTINCT count, which is what a batch lost mid-stream would move.
            conserved("min(CAST(ts AS DATETIME(3))), max(CAST(ts AS DATETIME(3))), count(DISTINCT ts)", "")

            // Grouped, so a lost or repeated batch lands in a few groups rather than in one total -- a
            // difference the aggregate totals above could in principle cancel out.
            conserved("grp, count(*), sum(id), min(id), max(id)", "GROUP BY grp ORDER BY grp")

            // A selective predicate: the source filters, so most batches come back empty or short, which
            // is a different shape of stream from a dense one.
            conserved("count(*), sum(id)", "WHERE id % 1000 = 0")
            conserved("count(*), min(id), max(id)", "WHERE id >= ${rows - 100}")
            // A predicate matching nothing at all.
            assertEquals(0L, sql("SELECT count(*) FROM ${table} WHERE id < 0")[0][0])
            // A predicate matching everything, so nothing is filtered but the WHERE clause is still built.
            conserved("count(*)", "WHERE id >= 0")

            // Limits over a large source: the scan must stop early without losing what it did return.
            assertEquals(10, sql("SELECT id FROM ${table} ORDER BY id LIMIT 10").size())
            assertEquals(0, sql("SELECT id FROM ${table} LIMIT 0").size())
            conserved("id, name", "ORDER BY id LIMIT 5")
            conserved("id, name", "ORDER BY id DESC LIMIT 5")
            conserved("id", "ORDER BY id LIMIT 5 OFFSET ${rows - 7}")

            // A join of the large table with itself: both inputs stream many batches at once.
            def selfJoin = sql """
                SELECT count(*) FROM ${table} a JOIN ${table} b ON a.id = b.id WHERE a.id % 10000 = 0
            """
            assertEquals((rows / 10000) as long, selfJoin[0][0],
                    "a self join over a multi-batch scan lost or duplicated rows")

            // The same data through the single-statement path, which streams one result set rather than
            // one per partition. Both must conserve the same rows.
            sql """
                CREATE CATALOG ${flightSingleRange} PROPERTIES (
                    "type" = "adbc",
                    "driver_url" = "${flightDriverPath}",
                    "uri" = "grpc://127.0.0.1:${arrowPort}",
                    "user" = "root",
                    "password" = "",
                    "partitioned_read" = "disabled"
                )
            """
            assertEquals(
                    sql("""SELECT count(*), count(DISTINCT id), sum(id), min(name), max(name)
                           FROM ${flightSingleRange}.${dbName}.big""").toString(),
                    sql("""SELECT count(*), count(DISTINCT id), sum(id), min(name), max(name)
                           FROM ${table}""").toString(),
                    "the partitioned and single-statement paths disagreed on a ${rows}-row read")

            qt_flight_large_summary """
                SELECT count(*), count(DISTINCT id), sum(id), min(id), max(id), count(maybe_null)
                FROM ${table}
            """
            qt_flight_large_grouped """
                SELECT grp, count(*) FROM ${table} GROUP BY grp ORDER BY grp LIMIT 10
            """
            qt_flight_large_head """SELECT id, name, grp FROM ${table} ORDER BY id LIMIT 5"""
            qt_flight_large_tail """SELECT id, name, grp FROM ${table} ORDER BY id DESC LIMIT 5"""
        }

        // ---- a SQLite file ----
        //
        // The other driver, and a different way into the same loop: one local statement streaming its
        // whole result rather than partitions of an already-executed query.

        if (!hasSqlite) {
            logger.info("test_adbc_large_data: SKIPPING the SQLite section, no driver at "
                    + "${sqliteDriverPath}. LARGE SINGLE-STATEMENT READS ARE NOT BEING TESTED.")
        } else {
            int sqliteRows = 120000
            String workDir = "${System.getProperty('java.io.tmpdir')}/doris_adbc_regression"
            new File(workDir).mkdirs()
            File dbFile = new File("${workDir}/test_adbc_large_data.db")
            File seedFile = new File("${workDir}/test_adbc_large_data.sql")
            dbFile.delete()

            // Generated inside SQLite rather than by ${sqliteRows} INSERT statements, which would make the
            // fixture the slowest part of the suite.
            seedFile.text = """
                CREATE TABLE big (id INTEGER, name TEXT, grp INTEGER, ratio REAL);
                WITH RECURSIVE cnt(x) AS (
                    SELECT 0 UNION ALL SELECT x + 1 FROM cnt WHERE x < ${sqliteRows - 1}
                )
                INSERT INTO big SELECT x, 'name-' || x, x % 97, x / 3.0 FROM cnt;
            """
            def seed = new ProcessBuilder("/bin/bash", "-c",
                    "sqlite3 '${dbFile.absolutePath}' < '${seedFile.absolutePath}'")
                    .redirectErrorStream(true).start()
            String seedOutput = seed.inputStream.text
            int seedExit = seed.waitFor()
            if (seedExit != 0 || !dbFile.exists()) {
                logger.info("test_adbc_large_data: SKIPPING the SQLite section, the fixture could not be "
                        + "built (exit ${seedExit}): ${seedOutput}. LARGE SINGLE-STATEMENT READS ARE NOT "
                        + "BEING TESTED.")
            } else {
                sql """
                    CREATE CATALOG ${sqliteCatalog} PROPERTIES (
                        "type" = "adbc",
                        "driver_url" = "${sqliteDriverPath}",
                        "uri" = "file:${dbFile.absolutePath}"
                    )
                """
                String sqliteTable = "${sqliteCatalog}.main.big"

                // No mirror table here, so the oracle is arithmetic: ids are 0..n-1, which has a closed
                // form for both the count and the sum. That is an independent answer in the strongest
                // sense -- it does not come from Doris at all.
                long expectedCount = sqliteRows
                long expectedSum = ((long) sqliteRows) * (sqliteRows - 1) / 2

                def summary = sql """
                    SELECT count(*), count(DISTINCT id), sum(id), min(id), max(id)
                    FROM ${sqliteTable}
                """
                assertEquals(expectedCount, summary[0][0] as long,
                        "a ${sqliteRows}-row SQLite table did not come back whole")
                assertEquals(expectedCount, summary[0][1] as long,
                        "rows were duplicated: ${summary[0][1]} distinct ids out of ${expectedCount}")
                assertEquals(expectedSum, summary[0][2] as long,
                        "the ids summed to the wrong total, so some batch was read at the wrong offset")
                assertEquals(0L, summary[0][3] as long)
                assertEquals(expectedCount - 1, summary[0][4] as long)

                // The string column, which has its own offset buffer per batch.
                def names = sql """
                    SELECT count(DISTINCT name), min(name), max(name) FROM ${sqliteTable}
                """
                assertEquals(expectedCount, names[0][0] as long,
                        "the string column lost or repeated values across batches")

                // Grouped: 97 groups spread evenly over every batch.
                def groups = sql """
                    SELECT count(*), sum(n) FROM (
                        SELECT grp, count(*) AS n FROM ${sqliteTable} GROUP BY grp
                    ) g
                """
                assertEquals(97L, groups[0][0] as long, "wrong number of groups")
                assertEquals(expectedCount, groups[0][1] as long, "the groups do not add up to the table")

                // A pushed predicate over a large scan.
                assertEquals(120L, sql("SELECT count(*) FROM ${sqliteTable} WHERE id % 1000 = 0")[0][0],
                        "a filtered multi-batch read returned the wrong count")
                assertEquals(100L, sql("SELECT count(*) FROM ${sqliteTable} WHERE id >= ${sqliteRows - 100}")[0][0])

                assertEquals(10, sql("SELECT id FROM ${sqliteTable} ORDER BY id LIMIT 10").size())

                qt_sqlite_large_summary """
                    SELECT count(*), count(DISTINCT id), sum(id), min(id), max(id) FROM ${sqliteTable}
                """
                qt_sqlite_large_head """SELECT id, name, grp FROM ${sqliteTable} ORDER BY id LIMIT 5"""
                qt_sqlite_large_tail """SELECT id, name, grp FROM ${sqliteTable} ORDER BY id DESC LIMIT 5"""
            }
        }
    } finally {
        sql """DROP CATALOG IF EXISTS ${flightCatalog}"""
        sql """DROP CATALOG IF EXISTS ${flightSingleRange}"""
        sql """DROP CATALOG IF EXISTS ${sqliteCatalog}"""
        sql """DROP DATABASE IF EXISTS internal.${dbName} FORCE"""
    }
}
