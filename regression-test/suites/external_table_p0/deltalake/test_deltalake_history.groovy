import groovy.json.JsonSlurper

suite("test_deltalake_history", "p0,external,deltalake,external_docker") {
    if (!"true".equalsIgnoreCase(context.config.otherConfigs.get("enableDeltaLakeTest"))) {
        return
    }
    String reference = context.config.otherConfigs.get("deltalakeHistoryReference")
    if (!reference) {
        logger.info("Set deltalakeHistoryReference to the reference generated by history-filesystem.py")
        return
    }
    String host = context.config.otherConfigs.get("externalEnvIp")
    String minioPort = context.config.otherConfigs.get("deltalakeMinioPort")
    String warehouse = context.config.otherConfigs.get("deltalakeWarehouse")
    def json = new JsonSlurper()
    def expectedRows = json.parse(new File(reference))

    sql "drop catalog if exists test_deltalake_history"
    String storage = warehouse.startsWith("file:") ? "" : """,
        's3.endpoint'='http://${host}:${minioPort}', 's3.region'='us-east-1',
        's3.access_key'='admin', 's3.secret_key'='password', 'use_path_style'='true'"""
    sql """create catalog test_deltalake_history properties (
        'type'='deltalake', 'deltalake.catalog.type'='filesystem', 'warehouse'='${warehouse}' ${storage}
    )"""
    sql "set time_zone='UTC'"
    String history = 'test_deltalake_history.delta_m1.`history_fixture$history`'
    String fields = """version, millisecond_timestamp(cast(timestamp as datetimev2(6))),
        userId, userName, operation, to_json(operationParameters), to_json(job), to_json(notebook),
        clusterId, readVersion, isolationLevel, isBlindAppend, to_json(operationMetrics),
        userMetadata, engineInfo"""
    def normalize = { row ->
        def values = row.toList()
        values[0] = values[0].longValue()
        values[9] = values[9]?.longValue()
        if (values[11] instanceof Number) {
            values[11] = values[11].intValue() != 0
        }
        [5, 6, 7, 12].each { index ->
            if (values[index] instanceof String) {
                values[index] = json.parseText(values[index])
            }
        }
        values
    }
    def expected = expectedRows.collect(normalize)
    sql "set enable_condition_cache=true"
    for (int attempt in 1..2) {
        def actual = sql("select ${fields} from ${history} where version >= 0 order by version").collect(normalize)
        assertEquals(expected, actual)
    }
    assertEquals(expected.findAll { it[0] >= 1 && it[0] <= 2 },
        sql("select ${fields} from ${history} where version >= 1 and version <= 2 order by version").collect(normalize))

    qt_schema "desc ${history}"
    qt_commits "select version, operation, userMetadata from ${history} order by version"
    qt_version "select version from ${history} where version = 2 order by version"
    qt_count "select count(*), count(userMetadata) from ${history}"
    qt_empty "select count(*) from ${history} where version < 0"
    order_qt_data "select id from test_deltalake_history.delta_m1.history_fixture"
    test {
        sql "select * from ${history} for version as of 1"
        exception "system tables do not support time travel"
    }
    test {
        sql "select * from ${history} for time as of '2026-01-01'"
        exception "system tables do not support time travel"
    }
}
