static std::vector<std::string> run(const GramScheme& s, std::string_view v) {
    GramExtractor ex(s);
    std::vector<std::string_view> out;
    ex.extract(v, &out);
    return {out.begin(), out.end()};
}

TEST(GramExtractorTest, DenseAsciiTrigrams) {
    GramScheme s;
    s.mode = GramMode::DENSE;
    s.min_len = 3;
    EXPECT_EQ(run(s, "abcde"), (std::vector<std::string> {"abc", "bcd", "cde"}));
    EXPECT_EQ(run(s, "ab"), (std::vector<std::string> {}));        // shorter than n: nothing
    EXPECT_EQ(run(s, "aaaa"), (std::vector<std::string> {"aaa"})); // deduped within the row
}

// Non-ASCII text is not indexed at all.
//
// It was, one term per code point, and that shape cannot be made to work. A term that is one
// character is too common to filter with, and every scheme that gives such a column a rarer
// term -- pairs, content-defined chunks of code points, pairs emitted only where both
// characters are common -- pays for it in vocabulary: measured on 500,000 rows of weibo the
// dictionary alone runs 5.5 MB to 22.8 MB against an 11.9 MB budget for the whole index,
// while one term per code point fits the dictionary and then needs its postings dropped to
// fit the budget, which leaves a CJK query with nothing to intersect. Six schemes, no
// configuration that is both small enough and useful.
//
// So the index declines the work rather than doing it badly. Correctness is unaffected: the
// extractor serves BOTH sides, so a literal's non-ASCII part contributes no gram to the query
// either, the candidate set is only ever widened, and the predicate re-checks every candidate
// row. A wholly non-ASCII pattern produces no grams at all and the query runs as a scan.
TEST(GramExtractorTest, NonAsciiTextProducesNoGrams) {
    GramScheme s;
    s.mode = GramMode::DENSE;
    EXPECT_EQ(run(s, "手机微博"), (std::vector<std::string> {}));
    // The ASCII segments of a mixed string still index, and still do not span the CJK that
    // separates them -- "abc" and "def" are two segments, not one six-byte run.
    EXPECT_EQ(run(s, "abc手机def"), (std::vector<std::string> {"abc", "def"}));
    // An invalid UTF-8 byte is non-ASCII too, and is skipped rather than indexed as itself.
    EXPECT_EQ(run(s, std::string("\xFF", 1)), (std::vector<std::string> {}));
    // A truncated sequence must not swallow the ASCII that follows it.
    EXPECT_EQ(run(s, std::string("\xe6\x89", 2) + "abc"), (std::vector<std::string> {"abc"}));
}

TEST(GramExtractorTest, SparseIsLocalAndDeterministic) {
    GramScheme s; // sparse p=0.25 n=3 L=16
    GramExtractor ex(s);
    // Locality: the gram set of any substring is a subset of the gram set of the whole string
    const std::string doc = "rpc error: code = Unavailable desc = error reading from server";
    std::vector<std::string_view> all;
    ex.extract(doc, &all);
    std::set<std::string> whole(all.begin(), all.end());
    for (size_t i = 0; i < doc.size(); i++) {
        for (size_t len = 3; i + len <= doc.size(); len++) {
            std::vector<std::string_view> sub;
            ex.extract(std::string_view(doc).substr(i, len), &sub);
            for (auto g : sub) {
                EXPECT_TRUE(whole.count(std::string(g))) << "gram '" << g << "' of substring [" << i
                                                         << "," << len << ") missing from whole";
            }
        }
    }
    // Density: at 0.25 the gram count is well below the dense count (len-2)
    EXPECT_LT(all.size(), (doc.size() - 2) / 2);
}

