// Covers Ruling R9: the extractor never emits a gram containing a NUL byte (0x00).
TEST(GramExtractorTest, NoGramContainsNulByte) {
    // DENSE n=3: all three windows of "ab\0cd" (5 bytes) -- "ab\0", "b\0c", "\0cd" -- contain NUL
    // and must all be skipped; the way window boundaries are computed is unchanged, they are just
    // not emitted.
    GramScheme dense;
    dense.mode = GramMode::DENSE;
    dense.min_len = 3;
    EXPECT_EQ(run(dense, std::string("ab\0cd", 5)), (std::vector<std::string> {}));

    // SPARSE: a NUL embedded in the middle of a longer string; candidate grams spanning the NUL
    // are skipped, while the parts far from it still emit grams as usual (locality is
    // unaffected).
    GramScheme sparse; // SPARSE by default, p=0.25 n=3 max_len=16
    GramExtractor ex(sparse);
    std::string doc = "rpc error: code = Unavailable desc = error reading from server";
    doc.insert(doc.begin() + 10, '\0');
    std::vector<std::string_view> out;
    ex.extract(doc, &out);
    ASSERT_FALSE(out.empty());
    for (const auto& g : out) {
        EXPECT_EQ(g.find('\0'), std::string_view::npos) << "gram '" << g << "' contains NUL";
    }
}

namespace {

// One row of `length` bytes drawn from the first `alphabet` printable ASCII characters. A narrow
// alphabet makes almost every window a repeat of an earlier one, a wide one makes almost every
// window unique, and alphabet=1 is the degenerate "one distinct gram, thousands of copies" case.
std::string random_ascii_row(uint64_t* seed, size_t length, unsigned alphabet) {
    std::string row;
    row.reserve(length);
    for (size_t i = 0; i < length; i++) {
        *seed = *seed * 6364136223846793005ULL + 1442695040888963407ULL;
        row.push_back(static_cast<char>(0x20 + (*seed >> 33) % alphabet));
    }
    return row;
}

} // namespace

// Deduplication must keep exactly the first occurrence of every distinct gram and leave the
// survivors in their original relative order. That order is a contract rather than an
// implementation detail -- TOKENIZE() hands it to the user, and the ordered assertions above pin
// it -- so a future rewrite of the dedupe step (to shrink its transient memory, say) must not
// disturb it. DENSE mode makes the contract checkable against an independent reference: over a
// NUL-free pure-ASCII row it emits exactly the min_len-byte windows in ascending start order, so
// the expected output is that window sequence run through a plain first-appearance dedupe.
TEST(GramExtractorTest, DenseDedupeKeepsOrderOfFirstAppearance) {
    const auto reference = [](const std::string& row, size_t min_len) {
        std::vector<std::string> expected;
        std::unordered_set<std::string_view> seen;
        for (size_t i = 0; i + min_len <= row.size(); i++) {
            const std::string_view window(row.data() + i, min_len);
            if (seen.insert(window).second) {
                expected.emplace_back(window);
            }
        }
        return expected;
    };
    uint64_t seed = 0x9e3779b97f4a7c15ULL;
    for (unsigned alphabet : {1U, 2U, 5U, 26U, 95U}) {
        for (size_t length : {size_t {1}, size_t {7}, size_t {64}, size_t {999}, size_t {4096}}) {
            const std::string row = random_ascii_row(&seed, length, alphabet);
            for (uint32_t min_len : {1U, 2U, 3U, 8U}) {
                GramScheme scheme;
                scheme.mode = GramMode::DENSE;
                scheme.min_len = min_len;
                SCOPED_TRACE("alphabet=" + std::to_string(alphabet) + " length=" +
                             std::to_string(length) + " min_len=" + std::to_string(min_len));
                EXPECT_EQ(run(scheme, row), reference(row, min_len));
            }
        }
    }
}

// SPARSE grams have variable length, so there is no equally short closed form for the emitted
// sequence; what must still hold on that path is that one row's gram list never repeats a gram.
TEST(GramExtractorTest, SparseOutputNeverRepeatsAGram) {
    uint64_t seed = 0x243f6a8885a308d3ULL;
    for (unsigned alphabet : {1U, 2U, 5U, 95U}) {
        for (size_t length : {size_t {3}, size_t {64}, size_t {4096}}) {
            std::string row = random_ascii_row(&seed, length, alphabet);
            row += "手机微博手机"; // a non-ASCII tail, which takes the 1-gram path
            GramScheme scheme;     // SPARSE by default, p=0.25 n=3 max_len=16
            SCOPED_TRACE("alphabet=" + std::to_string(alphabet) +
                         " length=" + std::to_string(length));
            const std::vector<std::string> grams = run(scheme, row);
            const std::set<std::string> distinct(grams.begin(), grams.end());
            EXPECT_EQ(grams.size(), distinct.size());
        }
    }
}

TEST(GramExtractorTest, BoundaryHashVersionOneGolden) {
    // Hash-version-1 goldens: FNV-1a over the 0/1 boundary results for all byte pairs in
    // numeric order. Pin the complete rule, not merely the approximate boundary density.
    struct Golden {
        uint32_t density;
        size_t count;
        uint64_t digest;
    };
    const Golden cases[] = {{.density = 1, .count = 76, .digest = 0xd82b5155d39e1de5ULL},
                            {.density = 250, .count = 16488, .digest = 0x90bb2e083a7a9ec5ULL},
                            {.density = 1000, .count = 65536, .digest = 0x2d438615f3572325ULL}};
    for (auto mode : {GramMode::DENSE, GramMode::SPARSE}) {
        for (const auto& golden : cases) {
            GramScheme scheme;
            scheme.mode = mode;
            scheme.density_permille = golden.density;
            SCOPED_TRACE(scheme.cache_key());
            GramExtractor extractor(scheme);
            size_t count = 0;
            uint64_t digest = 14695981039346656037ULL;
            for (unsigned pair = 0; pair < 65536; ++pair) {
                const bool boundary = extractor.is_boundary(static_cast<uint8_t>(pair >> 8),
                                                            static_cast<uint8_t>(pair));
                count += boundary;
                digest = (digest ^ boundary) * 1099511628211ULL;
            }
            EXPECT_EQ(count, golden.count);
            EXPECT_EQ(digest, golden.digest);
        }
    }
}

// A fresh tokenizer is created for each indexed value. Its setup must not dominate
// short-row extraction by an order of magnitude. Compare thread CPU time to exclude
// scheduling delays, and use a median with a deliberately generous local budget.
TEST(GramExtractorPerformanceTest, ShortRowsHaveBoundedConstructionOverhead) {
    const std::string row =
            "2026-09-05T12:45:30 INFO rpc request completed service=frontend "
            "method=query user=demo elapsed_ms=17 status=OK remote=10.1.2.3";
    constexpr size_t iterations = 1024;
    for (GramMode mode : {GramMode::DENSE, GramMode::SPARSE}) {
        GramScheme scheme;
        scheme.mode = mode;
        const size_t expected_grams = mode == GramMode::DENSE ? 120 : 28;
        std::array<double, 3> ratios {};
        for (double& ratio : ratios) {
            size_t fresh_count = 0;
            ThreadCpuStopWatch fresh_timer(true);
            for (size_t i = 0; i < iterations; ++i) {
                GramExtractor extractor(scheme);
                std::vector<std::string_view> grams;
                extractor.extract(row, &grams);
                fresh_count += grams.size();
            }
            fresh_timer.stop();

            GramExtractor extractor(scheme);
            std::vector<std::string_view> grams;
            size_t reused_count = 0;
            ThreadCpuStopWatch reused_timer(true);
            for (size_t i = 0; i < iterations; ++i) {
                extractor.extract(row, &grams);
                reused_count += grams.size();
            }
            reused_timer.stop();
            ASSERT_EQ(fresh_count, expected_grams * iterations);
            ASSERT_EQ(reused_count, expected_grams * iterations);
            ASSERT_GT(reused_timer.elapsed_time(), 0);
            ratio = static_cast<double>(fresh_timer.elapsed_time()) /
                    static_cast<double>(reused_timer.elapsed_time());
        }
        std::ranges::sort(ratios);
        RecordProperty(
                mode == GramMode::DENSE ? "dense_fresh_reused_ratio" : "sparse_fresh_reused_ratio",
                std::to_string(ratios[1]));
        EXPECT_LT(ratios[1], 10.0)
                << "mode=" << static_cast<int>(mode) << ", fresh/reused CPU ratio=" << ratios[1];
    }
}

