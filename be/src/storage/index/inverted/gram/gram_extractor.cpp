// symbol whose name another file of the same batch happens to reuse (even in a different .cpp),
// and the batching changes as files are added to or removed from the directory, so "this batch
// only holds these files" cannot be assumed for long. Hence the extra named namespace private
// to this file, which isolates this file's anonymous namespace; the symbols inside it still
// have internal linkage (anonymous-namespace semantics are unaffected by a named enclosing
// namespace).
namespace gram_extractor_detail {

namespace {

// The splitmix64 finalizer, used as the boundary hash mixing function for a byte pair (a,b); it
// must match mix64 in the prototype tools/regex-ngram-model/ngram_model.cpp bit for bit, because
// the golden data was generated by that prototype.
inline uint64_t mix64(uint64_t x) {
    x ^= x >> 30;
    x *= 0xbf58476d1ce4e5b9ULL;
    x ^= x >> 27;
    x *= 0x94d049bb133111ebULL;
    x ^= x >> 31;
    return x;
}

// Byte length (1/2/3/4) of the UTF-8 sequence starting with lead byte c; an illegal lead byte
// counts as 1.
inline int utf8_len(unsigned char c) {
    if (c < 0x80) {
        return 1;
    }
    if ((c >> 5) == 0x6) {
        return 2;
    }
    if ((c >> 4) == 0xE) {
        return 3;
    }
    if ((c >> 3) == 0x1E) {
        return 4;
    }
    return 1;
}

// Byte length of one valid UTF-8 code point starting at p; a truncated sequence or an invalid
// continuation byte (not 10xxxxxx) counts as illegal and returns 1 (handled as a single byte,
// emitted as a 1-gram).
inline size_t codepoint_len(const char* p, size_t remain) {
    int l = utf8_len((unsigned char)p[0]);
    if (l == 1 || (size_t)l > remain) {
        return 1;
    }
    for (int k = 1; k < l; k++) {
        if (((unsigned char)p[k] & 0xC0) != 0x80) {
            return 1;
        }
    }
    return l;
}

} // namespace

} // namespace gram_extractor_detail

GramExtractor::GramExtractor(const GramScheme& scheme) : _scheme(scheme) {
    _build_boundary_table();
}

void GramExtractor::_build_boundary_table() {
    _boundary_bits.assign(8192, 0);
    const uint64_t threshold = (uint64_t)_scheme.density_permille * 65536ULL / 1000ULL;
    for (unsigned idx = 0; idx < 65536; idx++) {
        uint64_t key = ((uint64_t)idx) ^ 0x5bd1e995ULL; // idx = (a<<8)|b
        if ((gram_extractor_detail::mix64(key) & 0xFFFF) < threshold) {
            _boundary_bits[idx >> 3] |= (uint8_t)(1U << (idx & 7));
        }
    }
}

void GramExtractor::_ascii_segment(std::string_view seg, std::vector<std::string_view>* out) {
    const size_t L = seg.size();
    const size_t n = _scheme.min_len;
    if (L < n) {
        return;
    }
    if (_scheme.mode == GramMode::DENSE) {
        for (size_t i = 0; i + n <= L; i++) {
            // Ruling R9: a candidate gram containing a NUL byte (0x00) is skipped entirely --
            // it is not emitted and does not affect the other windows, since computing the
            // window boundaries does not depend on NUL at all.
            std::string_view g = seg.substr(i, n);
            if (g.find('\0') == std::string_view::npos) {
                out->push_back(g);
            }
        }
        return;
    }
    // SPARSE: content-defined chunking (CDC). Starting at boundary k, extend to the first later
    // boundary j with j+2-k >= min_len, giving gram = [k, j+2); if no such boundary exists
    // within max_len, take the full window [k, k+max_len); if even the full window does not fit
    // (fewer than max_len bytes left before the end), this start position emits nothing.
    const size_t maxlen = _scheme.max_len;
    _is_boundary_at.assign(L, 0);
    for (size_t i = 0; i + 1 < L; i++) {
        _is_boundary_at[i] = is_boundary((uint8_t)seg[i], (uint8_t)seg[i + 1]);
    }
    for (size_t k = 0; k + 1 < L; k++) {
        if (!_is_boundary_at[k]) {
            continue;
        }
        size_t end = 0;
        for (size_t j = k + 1; j + 1 < L && j + 2 - k <= maxlen; j++) {
            if (_is_boundary_at[j] && j + 2 - k >= n) {
                end = j + 2;
                break;
            }
        }
        if (end == 0) {
            if (k + maxlen <= L) {
                end = k + maxlen;
            } else {
                continue;
            }
        }
        // Ruling R9: same as above -- a candidate gram containing NUL is skipped, and the
        // boundary (k/end) computation is unaffected.
        std::string_view g = seg.substr(k, end - k);
        if (g.find('\0') == std::string_view::npos) {
            out->push_back(g);
        }
    }
}

void GramExtractor::_dedupe(std::vector<std::string_view>* out) {
    std::unordered_set<std::string_view> seen;
    size_t w = 0;
    for (size_t r = 0; r < out->size(); r++) {
        if (seen.insert((*out)[r]).second) {
            (*out)[w++] = (*out)[r];
        }
    }
    out->resize(w);
}

void GramExtractor::extract(std::string_view value, std::vector<std::string_view>* out) {
    out->clear();
    if (_scheme.lower_case) {
        _folded.assign(value.data(), value.size());
        for (auto& ch : _folded) {
            if (ch >= 'A' && ch <= 'Z') {
                ch = (char)(ch - 'A' + 'a');
            }
        }
        value = _folded;
    }
    size_t i = 0;
    const size_t L = value.size();
    while (i < L) {
        if ((unsigned char)value[i] < 0x80) {
            // ASCII segment: scan forward to the first non-ASCII byte (or the end of the
            // string) and split the whole segment into grams at once.
            size_t j = i;
            while (j < L && (unsigned char)value[j] < 0x80) {
                j++;
            }
            _ascii_segment(value.substr(i, j - i), out);
            i = j;
        } else {
            // Non-ASCII: one valid code point (or one illegal byte) emits one 1-gram.
            size_t l = gram_extractor_detail::codepoint_len(value.data() + i, L - i);
            out->push_back(value.substr(i, l));
            i += l;
        }
    }
    _dedupe(out);
}

void GramExtractor::grams_of_literal(std::string_view s, std::vector<std::string>* out) {
    std::vector<std::string_view> tmp;
    extract(s, &tmp);
    out->assign(tmp.begin(), tmp.end());
}

