// The splitmix64 finalizer, used as the boundary hash mixing function for a byte pair (a,b); it
// must match mix64 in the prototype tools/regex-ngram-model/ngram_model.cpp bit for bit, because
// the golden data was generated by that prototype.
inline uint64_t mix64(uint64_t x) {
    x ^= x >> 30;
    x *= 0xbf58476d1ce4e5b9ULL;
    x ^= x >> 27;
    x *= 0x94d049bb133111ebULL;
    x ^= x >> 31;
    return x;
}

// Byte length (1/2/3/4) of the UTF-8 sequence starting with lead byte c; an illegal lead byte
// counts as 1.
inline int utf8_len(unsigned char c) {
    if (c < 0x80) {
        return 1;
    }
    if ((c >> 5) == 0x6) {
        return 2;
    }
    if ((c >> 4) == 0xE) {
        return 3;
    }
    if ((c >> 3) == 0x1E) {
        return 4;
    }
    return 1;
}

// Byte length of one valid UTF-8 code point starting at p; a truncated sequence or an invalid
// continuation byte (not 10xxxxxx) counts as illegal and returns 1 (handled as a single byte,
// emitted as a 1-gram).
inline size_t codepoint_len(const char* p, size_t remain) {
    int l = utf8_len((unsigned char)p[0]);
    if (l == 1 || (size_t)l > remain) {
        return 1;
    }
    for (int k = 1; k < l; k++) {
        if (((unsigned char)p[k] & 0xC0) != 0x80) {
            return 1;
        }
    }
    return l;
}

