GramExtractor::GramExtractor(const GramScheme& scheme)
        : _scheme(scheme),
          _boundary_threshold(static_cast<uint64_t>(scheme.density_permille) * 65536 / 1000) {}

void GramExtractor::set_density_permille(uint16_t density_permille) {
    _scheme.density_permille = density_permille;
    _boundary_threshold = static_cast<uint64_t>(density_permille) * 65536 / 1000;
}

uint16_t boundary_hash16(uint8_t a, uint8_t b) {
    const uint64_t key = ((static_cast<uint64_t>(a) << 8) | b) ^ 0x5bd1e995ULL;
    return static_cast<uint16_t>(gram_extractor_detail::mix64(key) & 0xFFFF);
}

bool GramExtractor::is_boundary(uint8_t a, uint8_t b) const {
    return boundary_hash16(a, b) < _boundary_threshold;
}

void GramExtractor::_ascii_segment(std::string_view seg, std::vector<std::string_view>* out) {
    const size_t L = seg.size();
    const size_t n = _scheme.min_len;
    if (L < n) {
        return;
    }
    if (_scheme.mode == GramMode::DENSE) {
        for (size_t i = 0; i + n <= L; i++) {
            // Ruling R9: a candidate gram containing a NUL byte (0x00) is skipped entirely --
            // it is not emitted and does not affect the other windows, since computing the
            // window boundaries does not depend on NUL at all.
            std::string_view g = seg.substr(i, n);
            if (g.find('\0') == std::string_view::npos) {
                out->push_back(g);
            }
        }
        return;
    }
    // SPARSE: content-defined chunking (CDC). Starting at boundary k, extend to the first later
    // boundary j with j+2-k >= min_len, giving gram = [k, j+2); if no such boundary exists
    // within max_len, take the full window [k, k+max_len); if even the full window does not fit
    // (fewer than max_len bytes left before the end), this start position emits nothing.
    const size_t maxlen = _scheme.max_len;
    _is_boundary_at.assign(L, 0);
    for (size_t i = 0; i + 1 < L; i++) {
        _is_boundary_at[i] = is_boundary((uint8_t)seg[i], (uint8_t)seg[i + 1]);
    }
    for (size_t k = 0; k + 1 < L; k++) {
        if (!_is_boundary_at[k]) {
            continue;
        }
        size_t end = 0;
        for (size_t j = k + 1; j + 1 < L && j + 2 - k <= maxlen; j++) {
            if (_is_boundary_at[j] && j + 2 - k >= n) {
                end = j + 2;
                break;
            }
        }
        if (end == 0) {
            if (k + maxlen <= L) {
                end = k + maxlen;
            } else {
                continue;
            }
        }
        // Ruling R9: same as above -- a candidate gram containing NUL is skipped, and the
        // boundary (k/end) computation is unaffected.
        std::string_view g = seg.substr(k, end - k);
        if (g.find('\0') == std::string_view::npos) {
            out->push_back(g);
        }
    }
}

// Deduplicate in place, keeping exactly the first occurrence of every distinct gram and leaving
// the survivors in their original relative order. That output order is a contract, not an
// implementation detail: TOKENIZE() hands it to the user and the ordered assertions in
// gram_extractor_test.cpp pin it, so any reordering here would be user-visible.
//
// The slot table replaces an std::unordered_set<std::string_view> that used to be built from
// scratch for every row. Both are one forward pass keeping first appearances -- the semantics are
// literally the same -- but the set paid ~40-48 bytes per candidate gram (a 32-byte libstdc++
// node: next pointer, cached hash, string_view; plus its share of the bucket array) and allocated
// all of it per row. This table is a reused member of 4 bytes per slot, so in the steady state it
// allocates nothing at all. Measured against the set it is never slower on any row length, mode
// or corpus, and roughly 1.7x faster at the median.
//
// Layout: slots hold indices into `out`, kEmpty marks a free slot, and the capacity is a power of
// two of at least 2n, so the table is at most half full -- linear probing always finds a free
// slot and the loop below always terminates.
void GramExtractor::_dedupe(std::vector<std::string_view>* out) {
    constexpr uint32_t kEmpty = std::numeric_limits<uint32_t>::max();
    const size_t n = out->size();
    if (n < 2) {
        return;
    }
    // A candidate gram is at least one byte long, so n never exceeds the row length, and the row
    // length is an int32_t on the tokenizer path (GramTokenizer::reset). Indices therefore always
    // fit in a uint32_t, and kEmpty can never collide with a real one.
    DCHECK_LT(n, static_cast<size_t>(kEmpty));
    size_t capacity = 8;
    while (capacity < n * 2) {
        capacity <<= 1;
    }
    // assign() on a buffer that is already large enough fills in place; only a row longer than
    // every row before it reallocates.
    _dedupe_slots.assign(capacity, kEmpty);
    const size_t mask = capacity - 1;
    const std::hash<std::string_view> hasher;
    size_t kept = 0;
    for (size_t r = 0; r < n; r++) {
        const std::string_view gram = (*out)[r];
        size_t slot = hasher(gram) & mask;
        while (true) {
            const uint32_t occupant = _dedupe_slots[slot];
            if (occupant == kEmpty) {
                // A slot stores the COMPACTED index, not the read cursor. Since kept <= r, the
                // survivor has already been written to its final position by the time anyone can
                // look it up, so (*out)[occupant] below is always a valid, settled gram -- which
                // is what lets the whole dedupe run in one in-place pass.
                _dedupe_slots[slot] = static_cast<uint32_t>(kept);
                (*out)[kept++] = gram;
                break;
            }
            if ((*out)[occupant] == gram) {
                break; // already seen: drop this occurrence, keep the earlier one
            }
            slot = (slot + 1) & mask;
        }
    }
    out->resize(kept);
}

void GramExtractor::extract(std::string_view value, std::vector<std::string_view>* out) {
    out->clear();
    if (_scheme.lower_case) {
        _folded.assign(value.data(), value.size());
        for (auto& ch : _folded) {
            if (ch >= 'A' && ch <= 'Z') {
                ch = (char)(ch - 'A' + 'a');
            }
        }
        value = _folded;
    }
    size_t i = 0;
    const size_t L = value.size();
    while (i < L) {
        if ((unsigned char)value[i] < 0x80) {
            // ASCII segment: scan forward to the first non-ASCII byte (or the end of the
            // string) and split the whole segment into grams at once.
            size_t j = i;
            while (j < L && (unsigned char)value[j] < 0x80) {
                j++;
            }
            _ascii_segment(value.substr(i, j - i), out);
            i = j;
        } else {
            // Non-ASCII: skipped, and it separates the ASCII segments around it.
            //
            // This used to emit one term per code point, and that shape has no working size.
            // A one-character term is too common to filter with -- measured on weibo, a
            // four-character literal with 18 matching rows proposed 500,000 candidates once
            // those postings were dropped to make the index fit. Every scheme that gives such
            // a column a rarer term instead pays in vocabulary: pairs, content-defined chunks
            // of code points, and pairs emitted only where both characters are common all
            // reach a dictionary of 5.5-22.8 MB against an 11.9 MB budget for the whole
            // index, because multi-character units in these scripts are combinatorially
            // diverse in a way that ASCII grams capped at max_gram bytes are not.
            //
            // Declining the work keeps the index honest. The extractor serves both the write
            // and the query side, so a literal's non-ASCII part contributes no gram to the
            // query either: the candidate set only ever widens, the predicate re-checks every
            // candidate row, and a wholly non-ASCII pattern compiles to no grams and runs as
            // a scan. Segments written when these terms were indexed stay readable for the
            // same reason -- a query simply stops asking for them.
            i += gram_extractor_detail::codepoint_len(value.data() + i, L - i);
        }
    }
    _dedupe(out);
}

void GramExtractor::grams_of_literal(std::string_view s, std::vector<std::string>* out) {
    std::vector<std::string_view> tmp;
    extract(s, &tmp);
    out->assign(tmp.begin(), tmp.end());
}

