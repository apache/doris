package org.apache.doris.connector.paimon;

import com.google.common.io.ByteStreams;
import org.apache.paimon.io.DataInputDeserializer;
import org.apache.paimon.io.DataOutputSerializer;
import org.apache.paimon.table.sink.CommitMessage;
import org.apache.paimon.table.sink.CommitMessageImpl;
import org.apache.paimon.table.sink.CommitMessageSerializer;
import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.Test;

import java.io.InputStream;
import java.util.Base64;
import java.util.List;

public class PaimonRustCommitMessageTest {
    @Test
    public void testRustAppendMessagesMatchJavaProtocol() throws Exception {
        // Generated by two independent paimon-rust 0.5.0-rc1 C FFI writers with
        // the upstream Java v14 serializer. Each wrote three INT rows to one Parquet file.
        byte[] bytes;
        try (InputStream input = getClass().getResourceAsStream("/paimon/rust-append-v14.base64")) {
            bytes = Base64.getMimeDecoder().decode(ByteStreams.toByteArray(input));
        }
        CommitMessageSerializer serializer = new CommitMessageSerializer();
        Assertions.assertEquals(14, serializer.getVersion());
        DataInputDeserializer input = new DataInputDeserializer(bytes);
        List<CommitMessage> messages = serializer.deserializeList(serializer.getVersion(), input);
        Assertions.assertEquals(0, input.available());
        Assertions.assertEquals(2, messages.size());
        for (CommitMessage message : messages) {
            CommitMessageImpl append = (CommitMessageImpl) message;
            Assertions.assertEquals(0, append.bucket());
            Assertions.assertNull(append.totalBuckets());
            Assertions.assertEquals(1, append.newFilesIncrement().newFiles().size());
            Assertions.assertEquals(3, append.newFilesIncrement().newFiles().get(0).rowCount());
            Assertions.assertEquals(0, append.newFilesIncrement().newFiles().get(0).schemaId());
            Assertions.assertTrue(append.compactIncrement().isEmpty());
        }
        DataOutputSerializer output = new DataOutputSerializer(bytes.length);
        serializer.serializeList(messages, output);
        Assertions.assertArrayEquals(bytes, output.getCopyOfBuffer());
        List<CommitMessage> upgraded = serializer.deserializeList(serializer.getVersion(),
                new DataInputDeserializer(output.getCopyOfBuffer()));
        Assertions.assertEquals(messages.size(), upgraded.size());
        for (int i = 0; i < messages.size(); i++) {
            Assertions.assertEquals(((CommitMessageImpl) messages.get(i)).newFilesIncrement().newFiles(),
                    ((CommitMessageImpl) upgraded.get(i)).newFilesIncrement().newFiles());
        }
    }
}
