package org.apache.doris.nereids.rules.rewrite;

import org.apache.doris.catalog.Env;
import org.apache.doris.nereids.CascadesContext;
import org.apache.doris.nereids.rules.Rule;
import org.apache.doris.nereids.rules.RuleType;
import org.apache.doris.nereids.trees.expressions.Expression;
import org.apache.doris.nereids.trees.expressions.IsNull;
import org.apache.doris.nereids.trees.expressions.Not;
import org.apache.doris.nereids.trees.expressions.Slot;
import org.apache.doris.nereids.trees.plans.Plan;
import org.apache.doris.nereids.trees.plans.algebra.OlapScan;
import org.apache.doris.nereids.trees.plans.logical.LogicalFilter;
import org.apache.doris.nereids.trees.plans.logical.LogicalJoin;
import org.apache.doris.nereids.util.ExpressionUtils;
import org.apache.doris.nereids.util.PlanUtils;
import org.apache.doris.nereids.util.TypeUtils;
import org.apache.doris.qe.ConnectContext;
import org.apache.doris.qe.SessionVariable;
import org.apache.doris.statistics.model.ColumnStatistic;

import com.google.common.collect.ImmutableList;
import com.google.common.collect.ImmutableSet;
import com.google.common.collect.Lists;
import com.google.common.collect.Sets;

import java.util.Collection;
import java.util.List;
import java.util.Optional;
import java.util.Set;

/**
 * Eliminate Predicate `is not null`, like
 * - redundant `is not null` predicate like `a > 0 and a is not null` -> `a > 0`
 * - `is not null` predicate is generated by `InferFilterNotNull`
 *
 * <p>The generated `is not null` predicate is not eliminated when it is evaluated directly on a scan and
 * the column has more nulls than {@link SessionVariable#KEEP_IS_NOT_NULL_NUM_NULLS_THRESHOLD}. The scan
 * can then skip the null values, which is worth more than the tiny cost of the extra predicate.
 */
public class EliminateNotNull implements RewriteRuleFactory {
    @Override
    public List<Rule> buildRules() {
        return ImmutableList.of(
                logicalFilter()
                        .when(EliminateNotNull::containsNot)
                        .thenApply(ctx -> {
                            LogicalFilter<Plan> filter = ctx.root;
                            Set<Expression> newConjuncts = ImmutableSet.copyOf(removeGeneratedNotNull(
                                    filter.getConjuncts(), ctx.cascadesContext, Optional.of(filter.child())));
                            // A kept generated `is not null` is rebuilt as a normal predicate, so compare the
                            // predicates instead of only their number.
                            if (newConjuncts.equals(filter.getConjuncts())) {
                                return null;
                            }
                            return PlanUtils.filterOrSelf(newConjuncts, filter.child());
                        }).toRule(RuleType.ELIMINATE_NOT_NULL),
                innerLogicalJoin()
                        .when(EliminateNotNull::containsNot)
                        .thenApply(ctx -> {
                            LogicalJoin<Plan, Plan> join = ctx.root;
                            List<Expression> newOtherJoinConjuncts = removeGeneratedNotNull(
                                    join.getOtherJoinConjuncts(), ctx.cascadesContext, Optional.empty());
                            if (newOtherJoinConjuncts.size() == join.getOtherJoinConjuncts().size()) {
                                return null;
                            }
                            return join.withJoinConjuncts(join.getHashJoinConjuncts(), newOtherJoinConjuncts,
                                        join.getJoinReorderContext());
                        })
                        .toRule(RuleType.ELIMINATE_NOT_NULL)
        );
    }

    /**
     * Remove the generated `is not null` predicates, but keep the ones worth pruning the scan.
     *
     * @param filterChild the child plan of the filter which owns the predicates, the generated
     *                    `is not null` predicate can only be kept when the predicates are evaluated
     *                    directly on a scan; empty if the predicates are join conditions.
     */
    private List<Expression> removeGeneratedNotNull(Collection<Expression> exprs, CascadesContext ctx,
            Optional<Plan> filterChild) {
        // Example: `id > 0 and id is not null and name is not null(generated)`
        // predicatesNotContainIsNotNull: `id > 0`
        // predicatesNotContainIsNotNull infer nonNullable slots: `id`
        // slotsFromIsNotNull: `id`, `name`
        // remove `name` (it's generated), remove `id` (because `id > 0` already contains it)
        Set<Expression> predicatesNotContainIsNotNull = Sets.newLinkedHashSet();
        List<Slot> slotsFromIsNotNull = Lists.newArrayList();
        OlapScan scan = filterChild.filter(OlapScan.class::isInstance)
                .map(OlapScan.class::cast)
                .orElse(null);
        long numNullsThreshold = scan == null ? -1 : getNumNullsThreshold(ctx);

        for (Expression expr : exprs) {
            // remove generated `is not null`, unless it is worth keeping for the scan pruning
            if (expr instanceof Not && ((Not) expr).isGeneratedIsNotNull()) {
                Optional<Slot> notNullSlot = TypeUtils.isNotNull(expr);
                if (notNullSlot.isPresent() && isWorthKeepingForScan(
                        notNullSlot.get(), scan, numNullsThreshold, ctx.getConnectContext())) {
                    slotsFromIsNotNull.add(notNullSlot.get());
                }
                continue;
            }
            Optional<Slot> notNullSlot = TypeUtils.isNotNull(expr);
            if (notNullSlot.isPresent()) {
                slotsFromIsNotNull.add(notNullSlot.get());
            } else {
                predicatesNotContainIsNotNull.add(expr);
            }
        }

        Set<Slot> inferNonNotSlots = ExpressionUtils.inferNotNullSlots(
                predicatesNotContainIsNotNull, ctx);

        ImmutableSet.Builder<Expression> keepIsNotNull
                = ImmutableSet.builderWithExpectedSize(slotsFromIsNotNull.size());
        for (Slot slot : slotsFromIsNotNull) {
            if (slot.nullable() && !inferNonNotSlots.contains(slot)) {
                keepIsNotNull.add(new Not(new IsNull(slot)));
            }
        }

        // merge predicatesNotContainIsNotNull and keepIsNotNull into a new List
        return ImmutableList.<Expression>builder()
                .addAll(predicatesNotContainIsNotNull)
                .addAll(keepIsNotNull.build())
                .build();
    }

    /**
     * The generated `is not null` predicate of a nullable column is worth keeping when the scan can use
     * it to skip the null values, that is, when the column has more nulls than the configured threshold.
     */
    private static boolean isWorthKeepingForScan(Slot slot, OlapScan scan, long numNullsThreshold,
            ConnectContext connectContext) {
        if (scan == null || numNullsThreshold < 0 || !slot.nullable()) {
            return false;
        }
        ColumnStatistic columnStatistic = Env.getCurrentEnv().getStatisticsCache()
                .getOlapTableStats(scan)
                .getColumnStatistics(slot.getName(), connectContext);
        return !columnStatistic.isUnKnown && columnStatistic.numNulls > numNullsThreshold;
    }

    private static long getNumNullsThreshold(CascadesContext ctx) {
        return ctx.getAndCacheSessionVariable(SessionVariable.KEEP_IS_NOT_NULL_NUM_NULLS_THRESHOLD,
                SessionVariable.DEFAULT_KEEP_IS_NOT_NULL_NUM_NULLS_THRESHOLD,
                sessionVariable -> sessionVariable.keepIsNotNullNumNullsThreshold);
    }

    private static boolean containsNot(Plan plan) {
        for (Expression expression : plan.getExpressions()) {
            if (expression.containsType(Not.class)) {
                return true;
            }
        }
        return false;
    }
}
