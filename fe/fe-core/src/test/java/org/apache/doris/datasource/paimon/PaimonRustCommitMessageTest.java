package org.apache.doris.datasource.paimon;

import com.google.common.io.ByteStreams;
import org.apache.paimon.io.DataInputDeserializer;
import org.apache.paimon.io.DataOutputSerializer;
import org.apache.paimon.table.sink.CommitMessage;
import org.apache.paimon.table.sink.CommitMessageImpl;
import org.apache.paimon.table.sink.CommitMessageSerializer;
import org.junit.Assert;
import org.junit.Test;

import java.io.InputStream;
import java.util.Base64;
import java.util.List;

public class PaimonRustCommitMessageTest {
    @Test
    public void testRustAppendMessagesMatchJavaProtocol() throws Exception {
        // Generated by two independent paimon-rust 0.4.0 C FFI writers with
        // the Doris v11 patch. Each wrote three INT rows to one Parquet file.
        byte[] bytes;
        try (InputStream input = getClass().getResourceAsStream("/paimon/rust-append-v11.base64")) {
            bytes = Base64.getMimeDecoder().decode(ByteStreams.toByteArray(input));
        }
        CommitMessageSerializer serializer = new CommitMessageSerializer();
        Assert.assertEquals(11, serializer.getVersion());
        DataInputDeserializer input = new DataInputDeserializer(bytes);
        List<CommitMessage> messages = serializer.deserializeList(11, input);
        Assert.assertEquals(0, input.available());
        Assert.assertEquals(2, messages.size());
        for (CommitMessage message : messages) {
            CommitMessageImpl append = (CommitMessageImpl) message;
            Assert.assertEquals(0, append.bucket());
            Assert.assertNull(append.totalBuckets());
            Assert.assertEquals(1, append.newFilesIncrement().newFiles().size());
            Assert.assertEquals(3, append.newFilesIncrement().newFiles().get(0).rowCount());
            Assert.assertEquals(0, append.newFilesIncrement().newFiles().get(0).schemaId());
            Assert.assertTrue(append.compactIncrement().isEmpty());
        }
        DataOutputSerializer output = new DataOutputSerializer(bytes.length);
        serializer.serializeList(messages, output);
        Assert.assertArrayEquals(bytes, output.getCopyOfBuffer());
    }
}
